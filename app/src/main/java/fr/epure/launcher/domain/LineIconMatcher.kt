    /**
     * @param roleIcon icône du rôle système de l'app (ex. « phone » pour le téléphone par défaut)
     * @return nom de l'icône Tabler, ou null
     */
    fun match(packageName: String, declaredCategory: Int = -1, roleIcon: String? = null): String? {
        byPackage[packageName]?.let { return it }
        roleIcon?.let { return it }
        val lower = packageName.lowercase()
        lower.split('.', '_').firstNotNullOfOrNull { bySegment[it] }?.let { return it }
        bySubstring.firstOrNull { (word, _) -> lower.contains(word) }?.let { return it.second }
        return byCategory[declaredCategory]
    }
